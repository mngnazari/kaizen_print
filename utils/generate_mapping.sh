#!/bin/bash
# ========================================
# اسکریپت تولید خودکار mapping.txt
# برای استفاده در لینوکس/مک
# ========================================

echo ""
echo "========================================"
echo "   ابزار تولید خودکار Mapping File"
echo "========================================"
echo ""

# چک کردن وجود پایتون
if ! command -v python3 &> /dev/null; then
    echo "[خطا] پایتون 3 نصب نیست!"
    echo "لطفا پایتون 3 را نصب کنید"
    exit 1
fi

# مسیر اسکریپت
SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"

# اجرای اسکریپت
echo "در حال تولید فایل mapping..."
echo ""

python3 "$SCRIPT_DIR/mapping_generator.py" "$@"

if [ $? -eq 0 ]; then
    echo ""
    echo "========================================"
    echo "   عملیات با موفقیت انجام شد!"
    echo "========================================"
    echo ""
    echo "فایل mapping.txt آماده ارسال به بات است."
    echo ""
else
    echo ""
    echo "[خطا] مشکلی در اجرا پیش آمد!"
    exit 1
fi
